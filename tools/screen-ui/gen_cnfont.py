"""Generate a 16x16 1-bpp bitmap table for the GB2312 character set.

The panel's C renderer has no font engine; SMS bodies are the only place with arbitrary text, so this
table (plus a Unicode -> glyph binary search) is what lets them show up.  Output is screen-ui/cn_font.h.
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONT = os.environ.get("CJK_FONT", r"C:\Windows\Fonts\simsun.ttc")
OUT = os.path.join(HERE, "cn_font.h")

chars = []
seen = set()
for hi in range(0xA1, 0xF8):
    for lo in range(0xA1, 0xFF):
        try:
            ch = bytes([hi, lo]).decode("gb2312")
        except UnicodeDecodeError:
            continue
        if len(ch) != 1:
            continue
        cp = ord(ch)
        if cp in seen:
            continue
        seen.add(cp)
        chars.append(cp)

chars.sort()
font = ImageFont.truetype(FONT, 16)

glyphs = []
for cp in chars:
    img = Image.new("L", (16, 16), 0)
    d = ImageDraw.Draw(img)
    d.text((0, 0), chr(cp), font=font, fill=255)
    rows = []
    for y in range(16):
        b0 = b1 = 0
        for x in range(16):
            if img.getpixel((x, y)) >= 64:
                if x < 8:
                    b0 |= 0x80 >> x
                else:
                    b1 |= 0x80 >> (x - 8)
        rows += [b0, b1]
    glyphs.append(rows)

print("glyphs:", len(chars))

with open(OUT, "w", encoding="ascii") as f:
    f.write("/* generated by gen_cnfont.py -- GB2312 16x16 1bpp */\n")
    f.write("#define CJK_N %d\n" % len(chars))
    f.write("static const unsigned short cjk_cp[CJK_N] = {\n")
    for i in range(0, len(chars), 12):
        f.write(",".join("0x%04X" % c for c in chars[i:i + 12]) + ",\n")
    f.write("};\n")
    f.write("static const unsigned char cjk_bits[CJK_N][32] = {\n")
    for rows in glyphs:
        f.write("{" + ",".join(str(v) for v in rows) + "},\n")
    f.write("};\n")

print("wrote", OUT, os.path.getsize(OUT), "bytes")
