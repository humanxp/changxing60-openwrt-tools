"""Render the fixed Chinese labels used by the status screen into a C header.

The status page is a 480x854 framebuffer drawn by a static C binary; there is no font engine on
the device.  Two sizes are embedded:

* 16 px for card titles and buttons (LABELS)
* 22 px for the five bottom-navigation labels (BIG) -- the nav bar is 84 px tall, 16 px looks
  lost in it, and scaling the 16 px bitmap 2x was too large.

Each label is a 1-bpp bitmap keyed by its UTF-8 string.
"""
from PIL import Image, ImageDraw, ImageFont
import os

LABELS = [
    "概览", "网络", "热点", "电池", "内存", "温度",
    "信号", "流量", "短信", "设置",
    "本次开机", "在线设备", "运行时间", "下载", "上传",
    "亮度", "切安卓", "重启", "实时速率", "已连接", "无",
    "正文请在 LuCI 查看", "邻区", "频段", "更新库", "刷新节点", "测速", "换快节点", "自动优选", "终端流量", "最新短信", "系统", "即将充满", "剩余", "充电", "确认", "取消",
    "运行中", "已停止", "节点", "连接", "面板",
]

BIG = ["概览", "信号", "流量", "短信", "设置"]

FONT = r"C:\Windows\Fonts\msyh.ttc"


def raster(text, size, font):
    img = Image.new("L", (size * len(text) + 10, size + 12), 0)
    d = ImageDraw.Draw(img)
    d.text((2, 2), text, font=font, fill=255)
    box = img.getbbox() or (0, 0, 1, 1)
    img = img.crop(box)
    w, h = img.size
    px = img.load()
    rows = []
    for y in range(h):
        bits = bytearray((w + 7) // 8)
        for x in range(w):
            if px[x, y] > 110:
                bits[x >> 3] |= 0x80 >> (x & 7)
        rows.append(bytes(bits))
    return w, h, b"".join(rows)


out = []
out.append("/* generated by gen_cn.py -- fixed Chinese labels as 1-bpp bitmaps */")
out.append("#ifndef CN_LABELS_H")
out.append("#define CN_LABELS_H")
out.append("struct cn_glyph { const char *txt; int w, h; const unsigned char *bits; };")

f16 = ImageFont.truetype(FONT, 16)
for i, s in enumerate(LABELS):
    w, h, data = raster(s, 16, f16)
    out.append("static const unsigned char cn_%d_bits[] = {%s};" % (i, ",".join(str(b) for b in data)))
    out.append('static const struct cn_glyph cn_%d = { "%s", %d, %d, cn_%d_bits };' % (i, s, w, h, i))
out.append("static const struct cn_glyph *cn_table[] = {%s};" % ",".join("&cn_%d" % i for i in range(len(LABELS))))
out.append("#define CN_COUNT %d" % len(LABELS))

f22 = ImageFont.truetype(FONT, 22)
for i, s in enumerate(BIG):
    w, h, data = raster(s, 22, f22)
    out.append("static const unsigned char cnb_%d_bits[] = {%s};" % (i, ",".join(str(b) for b in data)))
    out.append('static const struct cn_glyph cnb_%d = { "%s", %d, %d, cnb_%d_bits };' % (i, s, w, h, i))
out.append("static const struct cn_glyph *cn_big_table[] = {%s};" % ",".join("&cnb_%d" % i for i in range(len(BIG))))
out.append("#define CN_BIG_COUNT %d" % len(BIG))

out.append("""
static const struct cn_glyph *cn_find(const char *s)
{
	for (int i = 0; i < CN_COUNT; i++)
		if (strcmp(cn_table[i]->txt, s) == 0) return cn_table[i];
	return NULL;
}

static const struct cn_glyph *cn_big_find(const char *s)
{
	for (int i = 0; i < CN_BIG_COUNT; i++)
		if (strcmp(cn_big_table[i]->txt, s) == 0) return cn_big_table[i];
	return NULL;
}
#endif""")

dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "cn_labels.h")
open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("wrote", dst, os.path.getsize(dst), "bytes,", len(LABELS), "small,", len(BIG), "big")
